import { useEffect, useMemo, useState } from 'react'
import { API } from './auth'
import Logo from './Logo'
import { buildReportView, hostOf } from './report'

type Shared = { topic: string; title: string | null; report: string; updated_at: string }

/** Public, read-only page for a brief someone chose to share. No sign-in needed. */
export default function SharedView({ token }: { token: string }) {
  const [data, setData] = useState<Shared | null>(null)
  const [error, setError] = useState('')

  useEffect(() => {
    let live = true
    fetch(`${API}/shared/${encodeURIComponent(token)}`)
      .then(async response => {
        if (!live) return
        if (response.ok) setData((await response.json()) as Shared)
        else setError(response.status === 404 ? 'This shared brief does not exist, or the link was turned off.' : 'Could not load this brief right now.')
      })
      .catch(() => { if (live) setError('Cannot reach the server. Try again in a moment.') })
    return () => { live = false }
  }, [token])

  const view = useMemo(() => (data ? buildReportView(data.report) : null), [data])

  return <div className="shared-page">
    <header className="shared-top"><div className="brand"><Logo size={26} /><span>fieldwork<span className="brand-dot">.</span></span></div><a className="copy-button" href="#/">Open Fieldwork</a></header>
    <main className="shared-main">
      {!data && !error && <div className="auth-loading" role="status" aria-label="Loading"><span className="spinner" /></div>}
      {error && <div className="error-box" role="alert"><span>!</span> {error}</div>}
      {data && view && <section className="report-card">
        <div className="report-toolbar"><div className="report-label"><span className="report-check">✓</span><div><strong>Shared research brief</strong><small>Read-only · {data.topic}</small></div></div></div>
        <article className="markdown" dangerouslySetInnerHTML={{ __html: view.html }} />
        {view.sources.length > 0 && <section className="sources" aria-label="Sources"><h3>Sources</h3><ol>{view.sources.map(s => <li key={s.n} value={s.n}><a href={s.url} target="_blank" rel="noopener noreferrer">{s.title}</a><small>{hostOf(s.url)}</small></li>)}</ol></section>}
      </section>}
      <p className="shared-foot">Generated by an AI research assistant from public web sources. Check the cited sources before relying on it.</p>
    </main>
  </div>
}
